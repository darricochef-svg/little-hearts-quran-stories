import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sceneDir = path.join(root, 'assets', 'scenes');
const output = path.join(root, 'renders', 'episode-01-yunus-visual-review-only.mp4');
const ffmpeg = process.env.FFMPEG_PATH || 'ffmpeg';
const scenes = Array.from({ length: 6 }, (_, i) => path.join(sceneDir, 'scene-' + String(i + 1).padStart(2, '0') + '.ppm'));
for (const file of scenes) if (!fs.existsSync(file)) throw new Error('Missing scene asset: ' + file);
const args = ['-y', '-hide_banner', '-loglevel', 'warning'];
for (const file of scenes) args.push('-loop', '1', '-framerate', '30', '-t', '3', '-i', file);
const filters = scenes.map((_, i) => '[' + i + ':v]scale=1920:1080:force_original_aspect_ratio=decrease,pad=1920:1080:(ow-iw)/2:(oh-ih)/2,setsar=1,fps=30,format=yuv420p[v' + i + ']');
filters.push(scenes.map((_, i) => '[v' + i + ']').join('') + 'concat=n=6:v=1:a=0[vout]');
args.push('-filter_complex', filters.join(';'), '-map', '[vout]', '-an', '-c:v', 'libx264', '-preset', 'medium', '-crf', '22', '-movflags', '+faststart', output);
console.log('Building silent visual-only review preview; no narration, subtitles, or publication.');
const result = spawnSync(ffmpeg, args, { stdio: 'inherit', windowsHide: true });
if (result.error) throw result.error;
if (result.status !== 0) process.exit(result.status ?? 1);
console.log('Visual-only review preview:', output);
